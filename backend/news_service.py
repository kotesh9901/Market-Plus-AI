def _is_english_headline(title: str) -> bool:
    """
    Lightweight Unicode script filter.

    This rejects predominantly non-Latin-script headlines.
    It is not a full language detector.
    """

    characters = [
        char for char in _clean_text(title, 1000)
        if char.isalpha()
    ]

    if not characters:
        return False

    latin_count = sum(
        1
        for char in characters
        if "LATIN" in unicodedata.name(char, "")
    )

    return latin_count / len(characters) >= 0.75


