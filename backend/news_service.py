def _save_articles(
    articles: list[dict[str, Any]],
) -> int:

    if not articles:
        return 0

    saved_count = 0

    try:
        with get_db() as connection:
            columns = {
                row["name"]
                for row in connection.execute(
                    "PRAGMA table_info(news_articles)"
                ).fetchall()
            }

            required_columns = {
                "symbol",
                "title",
                "url",
                "source",
                "published_at",
                "summary",
                "sentiment",
                "sentiment_score",
                "created_at",
            }

            if not required_columns.issubset(columns):
                logger.warning(
                    "news_articles table is missing expected columns."
                )
                return 0

            for article in articles:
                title = _clean_text(article.get("title"), 1000)
                url = _clean_text(article.get("url"), 2000)

                if not title or not _canonical_url(url):
                    continue

                existing = connection.execute(
                    """
                    SELECT id
                    FROM news_articles
                    WHERE url = ?
                    LIMIT 1
                    """,
                    (url,),
                ).fetchone()

                values = (
                    _normalise_symbol(article.get("symbol")),
                    title,
                    _clean_text(article.get("source"), 200),
                    _clean_text(article.get("published_at"), 100),
                    _clean_text(article.get("summary"), 5000),
                    _clean_text(
                        article.get("sentiment") or "neutral",
                        30,
                    ),
                    float(article.get("sentiment_score") or 0.0),
                )

                if existing:
                    connection.execute(
                        """
                        UPDATE news_articles
                        SET symbol = ?,
                            title = ?,
                            source = ?,
                            published_at = ?,
                            summary = ?,
                            sentiment = ?,
                            sentiment_score = ?
                        WHERE id = ?
                        """,
                        values + (existing["id"],),
                    )

                else:
                    connection.execute(
                        """
                        INSERT INTO news_articles (
                            symbol,
                            title,
                            url,
                            source,
                            published_at,
                            summary,
                            sentiment,
                            sentiment_score,
                            created_at
                        )
                        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                        """,
                        (
                            values[0],
                            values[1],
                            url,
                            values[2],
                            values[3],
                            values[4],
                            values[5],
                            values[6],
                            _utc_iso(),
                        ),
                    )

                    saved_count += 1

    except Exception:
        logger.warning(
            "Could not persist news articles to SQLite.",
            exc_info=True,
        )

    return saved_count


# ---------------------------------------------------------------------------
# Public stock-news API
# ---------------------------------------------------------------------------

def get_stock_news(
    symbol: str | None = None,
    query: str | None = None,
    limit: int = DEFAULT_NEWS_LIMIT,
    refresh: bool = False,
) -> dict[str, Any]:

    clean_symbol = _normalise_symbol(symbol)
    clean_query = _normalise_query(query)
    clean_limit = _safe_limit(limit)

    cache_key = (
        f"stock-news:{clean_symbol}:{clean_query}:{clean_limit}"
    )

    if not refresh:
        cached = _cache_get(cache_key)

        if cached is not None:
            return cached

    company_name = (
        _resolve_company_name(clean_symbol)
        if clean_symbol and not clean_query
        else ""
    )

    search_queries = _build_search_queries(
        clean_symbol,
        clean_query,
    )

    articles: list[dict[str, Any]] = []
    successful_queries: list[str] = []

    for search_query in search_queries:
        if len(articles) >= clean_limit:
            break

        try:
            results = _fetch_articles(
                search_query=search_query,
                limit=clean_limit,
                requested_symbol=clean_symbol or None,
                company_name=company_name,
            )

        except Exception:
            logger.warning(
                "News retrieval failed for query %r.",
                search_query,
                exc_info=True,
            )
            continue

        if results:
            articles = _merge_articles(
                articles,
                results,
                clean_limit,
            )

            successful_queries.append(search_query)

    # Ensure each story contributes only once.
    articles = _deduplicate_articles(
        articles,
        limit=clean_limit,
    )

    # Recalculate sentiment after cross-query deduplication.
    for article in articles:
        sentiment = analyze_sentiment(article.get("title", ""))

        article.update({
            "sentiment": sentiment["sentiment"],
            "sentiment_score": sentiment["sentiment_score"],
            "sentiment_method": sentiment["sentiment_method"],
        })

    if articles:
        _save_articles(articles)

        providers_used = list(dict.fromkeys(
            article.get(
                "retrieval_provider",
                "Yahoo Finance",
            )
            for article in articles
        ))

        response = {
            "success": True,
            "symbol": clean_symbol or None,
            "query": successful_queries[0],
            "search_queries": successful_queries,
            "count": len(articles),
            "message": "News articles retrieved successfully.",
            "articles": articles,
            "retrieved_at": _utc_iso(),
            "provider": " + ".join(providers_used),
        }

    else:
        response = {
            "success": True,
            "symbol": clean_symbol or None,
            "query": clean_query or clean_symbol or "stock market",
            "search_queries": search_queries,
            "count": 0,
            "message": (
                "No relevant news articles were returned by the "
                "configured providers. No placeholder articles "
                "have been generated."
            ),
            "articles": [],
            "retrieved_at": _utc_iso(),
            "provider": (
                "NewsAPI with Yahoo Finance fallback"
                if str(getattr(Config, "NEWS_PROVIDER", "none"))
                .strip()
                .lower() == "newsapi"
                else "Yahoo Finance"
            ),
        }

    _cache_set(cache_key, response)
    return response


