def _resolve_company_name(symbol: str | None) -> str:
    clean_symbol = _normalise_symbol(symbol)

    if not clean_symbol:
        return ""

    try:
        ticker = yf.Ticker(clean_symbol)

        try:
            fast_info = ticker.fast_info

            if isinstance(fast_info, Mapping):
                name = (
                    fast_info.get("longName")
                    or fast_info.get("shortName")
                    or fast_info.get("name")
                )

                if name:
                    return _clean_text(name, 200)

        except Exception:
            logger.debug(
                "fast_info lookup failed for %s",
                clean_symbol,
            )

        try:
            info = ticker.get_info()

            if isinstance(info, Mapping):
                name = (
                    info.get("longName")
                    or info.get("shortName")
                    or info.get("displayName")
                )

                if name:
                    return _clean_text(name, 200)

        except Exception:
            logger.debug(
                "get_info lookup failed for %s",
                clean_symbol,
            )

    except Exception:
        logger.warning(
            "Company-name resolution failed for %s",
            clean_symbol,
        )

    return ""


def _remove_legal_suffix(company_name: str) -> str:
    suffix_pattern = (
        r"(?:\s+"
        r"(?:private\s+limited|pvt\.?\s*ltd\.?|limited|ltd\.?|"
        r"incorporated|inc\.?|corporation|corp\.?|plc|llc|llp)"
        r")+$"
    )

    return re.sub(
        suffix_pattern,
        "",
        _clean_text(company_name, 200),
        flags=re.IGNORECASE,
    ).strip()


# ---------------------------------------------------------------------------
# Search query construction
# ---------------------------------------------------------------------------

def _build_search_queries(
    symbol: str | None,
    query: str | None,
) -> list[str]:

    clean_symbol = _normalise_symbol(symbol)
    clean_query = _normalise_query(query)

    if clean_query:
        return [clean_query]

    if not clean_symbol:
        return ["stock market"]

    queries: list[str] = []

    company_name = _resolve_company_name(clean_symbol)

    if company_name:
        queries.append(company_name)

        short_name = _remove_legal_suffix(company_name)

        if (
            short_name
            and short_name.casefold() != company_name.casefold()
        ):
            queries.append(short_name)

    base_symbol = re.sub(
        r"\.(NS|BO)$",
        "",
        clean_symbol,
        flags=re.IGNORECASE,
    ).strip()

    if base_symbol:
        queries.append(base_symbol)

    queries.append(clean_symbol)

    unique = []
    seen = set()

    for item in queries:
        normalized = _normalise_query(item)
        key = normalized.casefold()

        if normalized and key not in seen:
            seen.add(key)
            unique.append(normalized)

    return unique[:MAX_SEARCH_ATTEMPTS]


# ---------------------------------------------------------------------------
# NewsAPI search
# ---------------------------------------------------------------------------

def _run_newsapi_search(
    query: str,
    limit: int = DEFAULT_NEWS_LIMIT,
) -> list[dict[str, Any]]:

    clean_query = _normalise_query(query)

    api_key = str(
        getattr(Config, "NEWS_API_KEY", "") or ""
    ).strip()

    if not clean_query or not api_key:
        return []

    try:
        response = requests.get(
            NEWSAPI_URL,
            headers={"X-Api-Key": api_key},
            params={
                "q": clean_query,
                "searchIn": "title,description",
                "language": "en",
                "sortBy": "relevancy",
                "pageSize": min(_safe_limit(limit), 100),
            },
            timeout=NEWSAPI_TIMEOUT_SECONDS,
        )

        response.raise_for_status()
        payload = response.json()

        if not isinstance(payload, dict):
            return []

        if payload.get("status") != "ok":
            logger.warning(
                "NewsAPI error: %s",
                _clean_text(payload.get("code"), 100),
            )
            return []

        raw_articles = payload.get("articles", [])

        if not isinstance(raw_articles, list):
            return []

        return [
            item for item in raw_articles
            if isinstance(item, dict)
        ]

    except requests.RequestException as exc:
        logger.warning(
            "NewsAPI request failed: %s",
            type(exc).__name__,
        )
        return []

    except (ValueError, TypeError):
        logger.warning("NewsAPI returned invalid JSON.")
        return []

    except Exception:
        logger.exception("Unexpected NewsAPI search error.")
        return []


# ---------------------------------------------------------------------------
# Yahoo Finance search
# ---------------------------------------------------------------------------

def _run_yahoo_search(
    query: str,
    limit: int = DEFAULT_NEWS_LIMIT,
) -> list[dict[str, Any]]:

    clean_query = _normalise_query(query)

    if not clean_query:
        return []

    try:
        search_result = yf.Search(
            clean_query,
            news_count=_safe_limit(limit),
            lists_count=0,
            include_research=False,
        )

        raw_news = getattr(search_result, "news", None)

        if not isinstance(raw_news, list):
            return []

        return [
            item for item in raw_news
            if isinstance(item, dict)
        ]

    except Exception:
        logger.warning(
            "Yahoo Finance news search failed for %r",
            clean_query,
        )
        return []


# ---------------------------------------------------------------------------
# Date and URL normalization
# ---------------------------------------------------------------------------

def _parse_datetime(value: Any) -> str:
    if value is None or value == "":
        return ""

    try:
        if isinstance(value, datetime):
            parsed = value

        elif isinstance(value, (int, float)):
            timestamp = float(value)

            if timestamp > 10_000_000_000:
                timestamp /= 1000

            parsed = datetime.fromtimestamp(
                timestamp,
                tz=timezone.utc,
            )

        elif isinstance(value, str):
            clean_value = value.strip()

            if clean_value.isdigit():
                timestamp = int(clean_value)

                if timestamp > 10_000_000_000:
                    timestamp /= 1000

                parsed = datetime.fromtimestamp(
                    timestamp,
                    tz=timezone.utc,
                )
            else:
                parsed = datetime.fromisoformat(
                    clean_value.replace("Z", "+00:00")
                )
        else:
            return ""

        if parsed.tzinfo is None:
            parsed = parsed.replace(tzinfo=timezone.utc)

        return parsed.astimezone(timezone.utc).isoformat()

    except (
        ValueError,
        TypeError,
        OverflowError,
        OSError,
    ):
        return ""


def _article_url(article: dict[str, Any]) -> str:
    candidates = [
        article.get("url"),
        article.get("link"),
    ]

    for key in ("canonicalUrl", "clickThroughUrl"):
        value = article.get(key)

        if isinstance(value, Mapping):
            candidates.append(value.get("url"))
        elif isinstance(value, str):
            candidates.append(value)

    for candidate in candidates:
        url = _clean_text(candidate, 2000)

        if _canonical_url(url):
            return url

    return ""


# ---------------------------------------------------------------------------
# Article normalization
# ---------------------------------------------------------------------------

def _normalize_article(
    raw_article: dict[str, Any],
    requested_symbol: str | None = None,
) -> dict[str, Any] | None:

    if not isinstance(raw_article, dict):
        return None

    article = dict(raw_article)
    content = raw_article.get("content")

    if isinstance(content, dict):
        merged = dict(content)

        for key, value in raw_article.items():
            if key != "content" and key not in merged:
                merged[key] = value

        article = merged

    title = _clean_text(
        article.get("title") or article.get("headline"),
        1000,
    )

    if not title or title.casefold() in {"[removed]", "removed"}:
        return None

    summary = _clean_text(
        article.get("description")
        or article.get("summary")
        or article.get("snippet")
        or article.get("text"),
        5000,
    )

    url = _article_url(article)

    # Do not display articles without a real provider URL.
    if not url:
        return None

    raw_source = article.get("source")

    if isinstance(raw_source, Mapping):
        raw_source = (
            raw_source.get("name")
            or raw_source.get("id")
        )

    publisher = article.get("publisher")

    if isinstance(publisher, Mapping):
        publisher = (
            publisher.get("displayName")
            or publisher.get("name")
        )

    provider = article.get("provider")

    if isinstance(provider, Mapping):
        provider = (
            provider.get("displayName")
            or provider.get("name")
        )

    source = _clean_text(
        raw_source or publisher or provider,
        200,
    )

    if not source:
        source = urlsplit(url).netloc

    published_value = (
        article.get("publishedAt")
        or article.get("published_at")
        or article.get("pubDate")
        or article.get("providerPublishTime")
        or article.get("displayTime")
    )

    published_at = _parse_datetime(published_value)

    raw_id = (
        article.get("uuid")
        or article.get("id")
        or article.get("articleId")
    )

    if raw_id:
        article_id = _clean_text(raw_id, 200)
    else:
        identity_text = f"{title}|{url}|{published_at}"

        article_id = hashlib.sha256(
            identity_text.encode("utf-8")
        ).hexdigest()[:32]

    return {
        "id": article_id,
        "symbol": _normalise_symbol(requested_symbol),
        "title": title,
        "summary": summary,
        "url": url,
        "source": source,
        "published_at": published_at,
        "sentiment": "neutral",
        "sentiment_score": 0.0,
        "sentiment_method": "rule_based",
        "retrieved_at": _utc_iso(),
    }


