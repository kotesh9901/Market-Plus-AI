# ---------------------------------------------------------------------------
# Aggregate news sentiment
# ---------------------------------------------------------------------------

def get_news_sentiment(
    symbol: str | None = None,
    query: str | None = None,
    limit: int = DEFAULT_NEWS_LIMIT,
    refresh: bool = False,
) -> dict[str, Any]:

    result = get_stock_news(
        symbol=symbol,
        query=query,
        limit=limit,
        refresh=refresh,
    )

    articles = result.get("articles", [])

    scores = [
        float(article.get("sentiment_score", 0.0))
        for article in articles
    ]

    if scores:
        average_score = sum(scores) / len(scores)

        if average_score >= 0.20:
            overall_sentiment = "positive"
        elif average_score <= -0.20:
            overall_sentiment = "negative"
        else:
            overall_sentiment = "neutral"

    else:
        average_score = 0.0
        overall_sentiment = "unavailable"

    sentiment_counts = {
        "positive": 0,
        "negative": 0,
        "neutral": 0,
    }

    for article in articles:
        label = article.get("sentiment", "neutral")

        if label in sentiment_counts:
            sentiment_counts[label] += 1

    return {
        "success": result.get("success", False),
        "symbol": result.get("symbol"),
        "query": result.get("query"),
        "search_queries": result.get("search_queries", []),
        "count": len(articles),
        "overall_sentiment": overall_sentiment,
        "average_sentiment_score": round(
            float(average_score),
            4,
        ),
        "sentiment_counts": sentiment_counts,
        "message": result.get("message", ""),
        "articles": articles,
        "retrieved_at": result.get("retrieved_at"),
        "provider": result.get("provider", "Yahoo Finance"),
        "sentiment_method": "rule_based",
    }
