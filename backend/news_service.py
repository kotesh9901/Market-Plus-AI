# ---------------------------------------------------------------------------
# General helpers
# ---------------------------------------------------------------------------

def _utc_now() -> datetime:
    return datetime.now(timezone.utc)


def _utc_iso() -> str:
    return _utc_now().isoformat()


def _clean_text(value: Any, max_length: int = 5000) -> str:
    if value is None:
        return ""

    if isinstance(value, Mapping):
        value = (
            value.get("text")
            or value.get("summary")
            or value.get("description")
            or value.get("name")
            or ""
        )

    if isinstance(value, (list, tuple)):
        value = " ".join(
            str(item) for item in value if item is not None
        )

    return re.sub(r"\s+", " ", str(value)).strip()[:max_length]


def _normalise_symbol(symbol: str | None) -> str:
    return str(symbol).strip().upper() if symbol else ""


def _normalise_query(query: str | None) -> str:
    return _clean_text(query, 200)


def _safe_limit(limit: Any) -> int:
    try:
        value = int(limit)
    except (TypeError, ValueError):
        value = DEFAULT_NEWS_LIMIT

    return max(1, min(value, MAX_NEWS_LIMIT))


def _normalise_words(value: str) -> list[str]:
    return re.findall(r"[a-z0-9]+", value.casefold())


def _normalise_for_matching(value: str) -> str:
    return " ".join(_normalise_words(value))


def _contains_phrase(text: str, phrase: str) -> bool:
    normalized_phrase = _normalise_for_matching(phrase)

    if not normalized_phrase:
        return False

    pattern = (
        r"(?<![a-z0-9])"
        + re.escape(normalized_phrase)
        + r"(?![a-z0-9])"
    )

    return bool(re.search(pattern, text))


def _canonical_url(url: str) -> str:
    """
    Normalize a URL for duplicate detection.

    The original provider URL is retained in the displayed article.
    """

    try:
        parts = urlsplit(url.strip())

        if parts.scheme.lower() not in {"http", "https"}:
            return ""

        if not parts.netloc:
            return ""

        path = parts.path.rstrip("/")

        return urlunsplit((
            parts.scheme.lower(),
            parts.netloc.lower(),
            path,
            "",
            "",
        )).casefold()

    except (TypeError, ValueError):
        return ""


