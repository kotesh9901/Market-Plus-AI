GENERIC_QUERY_WORDS = {
    "stock", "stocks", "share", "shares", "market",
    "markets", "company", "companies", "news",
    "finance", "financial", "limited", "private",
    "corporation", "inc", "ltd",
}

EVENT_ONLY_TERMS = {
    "marathon", "marathons", "runner", "runners",
    "charity", "athletics", "race", "races",
    "official insurance partner", "sponsorship",
    "sponsor", "sponsors",
}

BUSINESS_CONTEXT_TERMS = {
    "earnings", "revenue", "profit", "profits",
    "results", "quarter", "financial", "stock",
    "shares", "market", "contract", "client",
    "customer", "collaboration", "acquisition",
    "deal", "technology", "software", "cloud",
    "digital", "consulting", "services",
    "artificial intelligence", "investment",
    "dividend", "buyback", "order", "business",
    "layoff", "hiring", "workforce", "guidance",
    "outlook", "merger", "partnership",
}


def _build_company_aliases(
    search_query: str,
    requested_symbol: str | None = None,
    company_name: str | None = None,
) -> list[str]:

    aliases: list[str] = []

    for candidate in (
        company_name,
        _remove_legal_suffix(company_name or ""),
    ):
        candidate = _clean_text(candidate, 200)

        if candidate:
            aliases.append(candidate)

    clean_symbol = _normalise_symbol(requested_symbol)

    if clean_symbol:
        base_symbol = re.sub(
            r"\.(NS|BO)$",
            "",
            clean_symbol,
            flags=re.IGNORECASE,
        )

        if base_symbol:
            aliases.append(base_symbol)

    # A user-supplied company query can be one or multiple words.
    # Exclude generic market terms, but do not discard valid names
    # simply because they contain only one word.
    query_words = _normalise_words(search_query)

    if query_words:
        normalized_query = " ".join(query_words)

        if normalized_query not in GENERIC_QUERY_WORDS:
            aliases.append(search_query)

    unique = []
    seen = set()

    for alias in aliases:
        normalized = _normalise_for_matching(alias)

        if not normalized or normalized in seen:
            continue

        if normalized in GENERIC_QUERY_WORDS:
            continue

        seen.add(normalized)
        unique.append(alias)

    return unique


def _is_event_only_headline(title: str) -> bool:
    """
    Exclude obvious event-only stories when no business context exists.
    """

    has_event_term = any(
        _contains_phrase(title, term)
        for term in EVENT_ONLY_TERMS
    )

    if not has_event_term:
        return False

    has_business_context = any(
        _contains_phrase(title, term)
        for term in BUSINESS_CONTEXT_TERMS
    )

    return not has_business_context


def _is_relevant_article(
    article: dict[str, Any],
    search_query: str,
    requested_symbol: str | None = None,
    company_name: str | None = None,
) -> bool:
    """
    Strict stock-news rule:
    The company name or ticker must appear in the headline.

    A company mention only in the description is insufficient.
    """

    title = _normalise_for_matching(
        article.get("title", "")
    )

    if not title:
        return False

    normalized_query = _normalise_for_matching(search_query)

    # General market news is not tied to one company.
    if (
        not requested_symbol
        and normalized_query in {
            "stock market",
            "market news",
            "financial news",
        }
    ):
        return True

    aliases = _build_company_aliases(
        search_query=search_query,
        requested_symbol=requested_symbol,
        company_name=company_name,
    )

    if not aliases:
        return False

    headline_match = any(
        _contains_phrase(title, alias)
        for alias in aliases
    )

    if not headline_match:
        return False

    if _is_event_only_headline(title):
        return False

    return True


# ---------------------------------------------------------------------------
# Duplicate and syndicated-story detection
# ---------------------------------------------------------------------------

def _normalise_title_for_dedup(title: str) -> str:
    return _normalise_for_matching(title)


def _same_story(
    first: dict[str, Any],
    second: dict[str, Any],
) -> bool:

    first_url = _canonical_url(first.get("url", ""))
    second_url = _canonical_url(second.get("url", ""))

    if first_url and second_url and first_url == second_url:
        return True

    first_title = _normalise_title_for_dedup(
        first.get("title", "")
    )

    second_title = _normalise_title_for_dedup(
        second.get("title", "")
    )

    if not first_title or not second_title:
        return False

    if first_title == second_title:
        return True

    similarity = SequenceMatcher(
        None,
        first_title,
        second_title,
    ).ratio()

    if similarity >= 0.90:
        return True

    first_words = set(first_title.split())
    second_words = set(second_title.split())

    union = first_words | second_words

    if not union:
        return False

    overlap = len(first_words & second_words) / len(union)

    return overlap >= 0.88


def _deduplicate_articles(
    articles: list[dict[str, Any]],
    limit: int | None = None,
) -> list[dict[str, Any]]:
    """
    Preserve the first provider result for each story.
    Never create or merge article content.
    """

    unique: list[dict[str, Any]] = []

    for article in articles:
        if any(
            _same_story(article, existing)
            for existing in unique
        ):
            continue

        unique.append(article)

        if limit is not None and len(unique) >= limit:
            break

    return unique


# ---------------------------------------------------------------------------
# Article retrieval
# ---------------------------------------------------------------------------

def _fetch_articles(
    search_query: str,
    limit: int,
    requested_symbol: str | None = None,
    company_name: str | None = None,
) -> list[dict[str, Any]]:

    use_newsapi = (
        str(getattr(Config, "NEWS_PROVIDER", "none"))
        .strip()
        .lower() == "newsapi"
        and bool(getattr(Config, "NEWS_API_KEY", ""))
    )

    providers = (
        [
            ("NewsAPI", _run_newsapi_search),
            ("Yahoo Finance", _run_yahoo_search),
        ]
        if use_newsapi
        else [("Yahoo Finance", _run_yahoo_search)]
    )

    for provider_name, search_function in providers:
        raw_articles = search_function(search_query, limit)

        normalized_articles = []

        for raw_article in raw_articles:
            normalized = _normalize_article(
                raw_article,
                requested_symbol=requested_symbol,
            )

            if not normalized:
                continue

            if not _is_english_headline(normalized["title"]):
                continue

            if not _is_relevant_article(
                normalized,
                search_query,
                requested_symbol,
                company_name,
            ):
                continue

            # Use the headline only for sentiment.
            # Descriptions can contain promotional language that
            # may distort the sentiment score.
            sentiment = analyze_sentiment(
                normalized["title"]
            )

            normalized.update({
                "sentiment": sentiment["sentiment"],
                "sentiment_score": sentiment["sentiment_score"],
                "sentiment_method": sentiment["sentiment_method"],
                "retrieval_provider": provider_name,
            })

            normalized_articles.append(normalized)

        normalized_articles = _deduplicate_articles(
            normalized_articles,
            limit=limit,
        )

        # Yahoo Finance is used only when NewsAPI has no relevant
        # articles for this particular query.
        if normalized_articles:
            return normalized_articles

    return []


# ---------------------------------------------------------------------------
# Cross-query merging
# ---------------------------------------------------------------------------

def _merge_articles(
    existing: list[dict[str, Any]],
    incoming: list[dict[str, Any]],
    limit: int,
) -> list[dict[str, Any]]:

    return _deduplicate_articles(
        list(existing) + list(incoming),
        limit=limit,
    )


